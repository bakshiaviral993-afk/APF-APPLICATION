// Generate 400 Units deterministically with rich realistic details
export function generate400Units(): UnitItem[] {
  const units: UnitItem[] = [];
  const configs: Array<'2 BHK' | '3 BHK' | '4 BHK' | 'Penthouse'> = ['2 BHK', '3 BHK', '3 BHK', '4 BHK'];
  const commonSurnames = ['Sharma', 'Verma', 'Kulkarni', 'Deshmukh', 'Patel', 'Mehta', 'Nair', 'Iyer', 'Reddy', 'Chauhan', 'Gupta', 'Bose'];
  const commonFirstNames = ['Amit', 'Sunita', 'Rahul', 'Pooja', 'Sandeep', 'Neha', 'Vikram', 'Deepika', 'Kunal', 'Ananya', 'Rohan', 'Swati'];

  let globalIdx = 1;

  DEMO_TOWERS.forEach((tower) => {
    const unitsPerFloor = Math.ceil(tower.unitsCount / tower.floors);

    for (let floor = 1; floor <= tower.floors; floor++) {
      for (let u = 1; u <= unitsPerFloor; u++) {
        if (units.filter(x => x.towerId === tower.id).length >= tower.unitsCount) break;

        const unitNumber = `${tower.name.split(' ')[1]}-${floor * 100 + u}`;
        const isPenthouse = floor >= 19;
        const config = isPenthouse ? 'Penthouse' : configs[(floor + u) % configs.length];
        const carpetAreaSqFt = config === '2 BHK' ? 685 : config === '3 BHK' ? 980 : config === '4 BHK' ? 1420 : 2180;
        const ratePerSqFt = 18500 + ((floor - 1) * 150) + (u % 2 === 0 ? 300 : 0);
        const agreementValueLakh = Math.round((carpetAreaSqFt * ratePerSqFt) / 100000);
        const marketValuationLakh = Math.round(agreementValueLakh * (1 + ((u % 5 - 2) * 0.02)));

        // Determine status according to tower distribution
        let status: 'Funded' | 'Pipeline' | 'Delinquent' | 'Booked' | 'Unsold' = 'Unsold';
        let dpd: '0 DPD' | '1-30 DPD' | '31-60 DPD' | '61-90 DPD' | '90+ DPD' = '0 DPD';

        const hash = (floor * 13 + u * 7 + globalIdx) % 100;

        if (tower.id === 'TOW-02' && (floor === 7 || floor === 8 || floor === 9) && u <= 2) {
          // Controlled delinquency in Tower B for demonstration!
          status = 'Delinquent';
          dpd = '31-60 DPD';
        } else if (hash < 55) {
          status = 'Funded';
          dpd = '0 DPD';
        } else if (hash < 68) {
          status = 'Pipeline';
        } else if (hash < 82) {
          status = 'Booked';
        } else {
          status = 'Unsold';
        }

        const isLinkedToBank = status === 'Funded' || status === 'Delinquent' || status === 'Pipeline';
        const fn = commonFirstNames[(globalIdx + floor) % commonFirstNames.length];
        const sn = commonSurnames[(globalIdx + u) % commonSurnames.length];
        const borrowerName = isLinkedToBank ? `${fn} ${sn}` : undefined;
        const loanAccountNo = isLinkedToBank ? `HL-MUM-26-${10000 + globalIdx}` : undefined;
        const sanctionAmountLakh = isLinkedToBank ? Math.round(agreementValueLakh * 0.78) : undefined;
        const disbursedAmountLakh = status === 'Pipeline' ? Math.round(sanctionAmountLakh! * 0.3) : isLinkedToBank ? Math.round(sanctionAmountLakh! * 0.92) : undefined;
        const outstandingAmountLakh = isLinkedToBank ? (status === 'Pipeline' ? disbursedAmountLakh : Math.round(disbursedAmountLakh! * 0.95)) : undefined;
        const ltvPct = isLinkedToBank ? Number(((sanctionAmountLakh! / agreementValueLakh) * 100).toFixed(1)) : undefined;

        units.push({
          id: `UNIT-${globalIdx}`,
          unitNumber,
          towerId: tower.id,
          towerName: tower.name,
          floor,
          configuration: config,
          carpetAreaSqFt,
          agreementValueLakh,
          marketValuationLakh,
          status,
          borrowerName,
          loanAccountNo,
          sanctionAmountLakh,
          disbursedAmountLakh,
          outstandingAmountLakh,
          ltvPct,
          dpdBucket: status === 'Delinquent' ? dpd : '0 DPD',
          valuationDeviationPct: Number((((marketValuationLakh - agreementValueLakh) / agreementValueLakh) * 100).toFixed(1)),
        });

        globalIdx++;
      }
    }
  });

  return units;
}

