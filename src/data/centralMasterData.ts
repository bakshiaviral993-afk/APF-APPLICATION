// Helper to generate realistic unit master for towers
function generateUnitsForTower(
  towerId: string,
  floors: number,
  unitsPerFloor: number,
  prefix: string,
  baseRateSqFt: number
): UnitMaster[] {
  const units: UnitMaster[] = [];
  for (let f = 1; f <= Math.min(floors, 10); f++) {
    for (let u = 1; u <= unitsPerFloor; u++) {
      const is3Bhk = u % 2 === 0;
      const carpet = is3Bhk ? 1050 : 740;
      const unitNum = `${prefix}-${f * 100 + u}`;
      const agrValLakh = Math.round((carpet * baseRateSqFt * (1 + f * 0.005)) / 100000);
      const isFunded = (f + u) % 4 === 0;
      const isBooked = (f + u) % 3 === 0;

      units.push({
        id: `UNT-${towerId}-${unitNum}`,
        towerId: towerId,
        unitNumber: unitNum,
        floorNumber: f,
        typology: is3Bhk ? '3 BHK' : '2 BHK',
        carpetAreaSqFt: carpet,
        agreementValueLakh: agrValLakh,
        status: isFunded ? 'Funded' : isBooked ? 'Booked' : 'Available',
        borrowerName: isFunded ? `Borrower ${unitNum} (Sourced Home Loan)` : undefined,
        loanAccountNumber: isFunded ? `HL-SBI-${f * 1000 + u * 12}` : undefined,
        isSimulatedPocUnit: true,
      });
    }
  }
  return units;
}

